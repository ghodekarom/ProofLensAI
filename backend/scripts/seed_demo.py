"""Demo Seeder script for ProofLens AI.

Creates a demonstration workspace with two realistic technical sample PDFs:
1. architecture_overview.pdf (System design, pgvector, PyMuPDF extraction, chunking)
2. evaluation_guide.pdf (Retrieval metrics, citation validity, cross-document comparison)

Usage:
    python backend/scripts/seed_demo.py
"""

from __future__ import annotations

import sys
from pathlib import Path

# Add backend/src to path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

import fitz

from prooflens.db.session import get_session_factory
from prooflens.schemas.workspaces import WorkspaceCreate
from prooflens.services.ingestion import IngestionService
from prooflens.services.workspaces import WorkspaceService


def create_pdf(pages: list[str]) -> bytes:
    doc = fitz.open()
    for text in pages:
        page = doc.new_page(width=595, height=842)
        page.insert_text((50, 72), text, fontsize=12)
    pdf_bytes = doc.tobytes()
    doc.close()
    return pdf_bytes


def seed_demo_workspace() -> None:
    session_factory = get_session_factory()
    with session_factory() as db:
        ws_svc = WorkspaceService(db)
        ingestion_svc = IngestionService(db)

        # 1. Create Workspace
        workspace = ws_svc.create(
            WorkspaceCreate(
                name="ProofLens Showcase Workspace",
                description="Pre-seeded demonstration workspace featuring technical design and evaluation PDFs.",
            )
        )
        print(f"\nCreated Workspace: {workspace.name} (ID: {workspace.id})")

        # 2. Seed Document 1: Architecture Overview
        doc1_bytes = create_pdf([
            (
                "ProofLens AI Architecture Overview — Page 1\n\n"
                "The ProofLens AI platform implements evidence-grounded document intelligence.\n"
                "PDF ingestion extracts clean text streams using PyMuPDF (fitz) with strict page tracking.\n"
                "Chunking builds 800-token windows with 120-token overlap, retaining exact page provenance.\n"
                "Upload deduplication verifies SHA-256 hashes to prevent redundant processing."
            ),
            (
                "ProofLens AI Architecture Overview — Page 2\n\n"
                "High-dimensional vector storage is powered by PostgreSQL with the pgvector extension.\n"
                "Embeddings are generated at 768 dimensions using Gemini Embedding 2.\n"
                "Approximate nearest neighbour (ANN) retrieval uses IVFFlat cosine distance indexing.\n"
                "Hard cascade deletion cleanly purges documents, chunks, vectors, and physical files."
            ),
        ])
        doc1 = ingestion_svc.upload_document(
            workspace_id=workspace.id,
            filename="architecture_overview.pdf",
            content=doc1_bytes,
        )
        print(f"Uploaded and Indexed: {doc1.original_filename} (ID: {doc1.id})")

        # 3. Seed Document 2: Evaluation Guide
        doc2_bytes = create_pdf([
            (
                "ProofLens AI Evaluation Benchmark Guide — Page 1\n\n"
                "Traceability is the core value proposition of ProofLens AI.\n"
                "Every factual answer generated by Gemini 3.8 Flash must include explicit [Page N] citations.\n"
                "Retrieval Hit Rate measures the percentage of queries where the true target passage is retrieved.\n"
                "Citation Validity Rate enforces that all cited references correspond to real extracted chunks."
            ),
            (
                "ProofLens AI Evaluation Benchmark Guide — Page 2\n\n"
                "Cross-document comparison evaluates findings across at least two documents on a shared topic.\n"
                "The relationship between documents is classified into: supports, differs, apparent_contradiction, or not_comparable.\n"
                "Deterministic abstention ensures the system answers 'insufficient evidence' rather than hallucinating."
            ),
        ])
        doc2 = ingestion_svc.upload_document(
            workspace_id=workspace.id,
            filename="evaluation_guide.pdf",
            content=doc2_bytes,
        )
        print(f"Uploaded and Indexed: {doc2.original_filename} (ID: {doc2.id})")

        print("\nDemo workspace seeded successfully! You can now query and compare documents.")


if __name__ == "__main__":
    seed_demo_workspace()
